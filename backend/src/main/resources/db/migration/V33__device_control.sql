CREATE TABLE IF NOT EXISTS biz_device_control_config (
  config_id BIGINT NOT NULL AUTO_INCREMENT,
  company_id BIGINT NULL,
  equipment_id BIGINT NOT NULL,
  brand VARCHAR(40) NOT NULL DEFAULT 'SIEMENS_LOGO',
  protocol VARCHAR(30) NOT NULL DEFAULT 'SIMULATOR',
  enabled CHAR(1) NOT NULL DEFAULT '1',
  host VARCHAR(100) NULL,
  port INT NOT NULL DEFAULT 502,
  unit_id INT NOT NULL DEFAULT 1,
  area VARCHAR(20) NOT NULL DEFAULT 'HOLDING',
  start_address INT NULL,
  stop_address INT NULL,
  run_status_address INT NULL,
  local_remote_address INT NULL,
  interlock_address INT NULL,
  fault_address INT NULL,
  write_value INT NOT NULL DEFAULT 1,
  timeout_ms INT NOT NULL DEFAULT 3000,
  remark VARCHAR(500) NULL,
  create_by VARCHAR(64) NULL,
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_by VARCHAR(64) NULL,
  update_time DATETIME NULL,
  PRIMARY KEY (config_id),
  UNIQUE KEY uk_control_equipment (equipment_id),
  KEY idx_control_company (company_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='设备远程控制配置';

CREATE TABLE IF NOT EXISTS biz_control_command (
  command_id BIGINT NOT NULL AUTO_INCREMENT,
  command_no VARCHAR(64) NOT NULL,
  company_id BIGINT NULL,
  equipment_id BIGINT NOT NULL,
  equipment_name VARCHAR(200) NULL,
  action VARCHAR(10) NOT NULL,
  status VARCHAR(20) NOT NULL,
  request_id VARCHAR(100) NOT NULL,
  reason VARCHAR(500) NULL,
  confirm_text VARCHAR(100) NULL,
  operator_id BIGINT NULL,
  operator_name VARCHAR(64) NULL,
  before_status VARCHAR(100) NULL,
  after_status VARCHAR(100) NULL,
  error_message VARCHAR(500) NULL,
  detail_json TEXT NULL,
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  finish_time DATETIME NULL,
  PRIMARY KEY (command_id),
  UNIQUE KEY uk_control_command_no (command_no),
  UNIQUE KEY uk_control_request (request_id),
  KEY idx_control_command_equipment (equipment_id, create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='设备控制命令审计';
